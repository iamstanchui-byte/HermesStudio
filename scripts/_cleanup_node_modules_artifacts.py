"""One-shot cleanup: delete the 373 spurious node_modules/* artifact rows
left over from the v3.10.3 wrapper bug (proj-5b0e6724, task 443bc94c).

The wrapper's auto-upload loop uploaded every file under cache_root
including node_modules/, producing 373 audit_log events + DB rows
for files that aren't deliverables. This script removes the artifact
rows AND the audit_log entries. Run once and forget.

Usage:
    cd "C:/Project/minimax code/hermes-orchestrator"
    python scripts/_cleanup_node_modules_artifacts.py

Destructive — backs up first, asks for confirmation, prints what it
will delete before doing anything.
"""
from __future__ import annotations

import io
import json
import shutil
import sqlite3
import sys
from pathlib import Path

# Force UTF-8 stdout so the '->' arrows print cleanly on Windows
# cp1252 consoles (default on this box).
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
else:
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

DB_PATH = Path("C:/Users/stanley/.hermes-orchestrator/hermes-orch.db")
BACKUP_PATH = DB_PATH.with_suffix(".db.pre-node-modules-cleanup")


def main() -> int:
    if not DB_PATH.exists():
        print(f"DB not found: {DB_PATH}")
        return 1

    # 1) Backup
    print(f"Backing up DB -> {BACKUP_PATH}")
    shutil.copy2(DB_PATH, BACKUP_PATH)
    print(f"  backup size: {BACKUP_PATH.stat().st_size:,} bytes")

    conn = sqlite3.connect(str(DB_PATH))
    cur = conn.cursor()

    # 2) What will be deleted (artifacts)
    n_art = cur.execute(
        "SELECT COUNT(*) FROM artifacts WHERE name LIKE 'node_modules/%'"
    ).fetchone()[0]
    print(f"\nArtifacts to delete: {n_art}")
    # Show sample
    for r in cur.execute(
        "SELECT id, project_id, task_id, name FROM artifacts "
        "WHERE name LIKE 'node_modules/%' LIMIT 5"
    ).fetchall():
        print(f"  {r[0][:12]}  proj={r[1]}  task={r[2][:8] if r[2] else 'None'}  {r[3]}")

    # 3) What will be deleted (audit_log events for those artifacts)
    n_aud = cur.execute(
        "SELECT COUNT(*) FROM audit_log WHERE event_type = 'artifact.registered' "
        "AND json_extract(payload, '$.path') LIKE 'node_modules/%'"
    ).fetchone()[0]
    print(f"\nAudit log entries to delete: {n_aud}")

    # Total DB size
    cur.execute("SELECT COUNT(*) FROM artifacts")
    n_total_art = cur.fetchone()[0]
    cur.execute("SELECT COUNT(*) FROM audit_log")
    n_total_aud = cur.fetchone()[0]
    print(f"\n  artifacts total before: {n_total_art}  ->  after: {n_total_art - n_art}")
    print(f"  audit_log total before: {n_total_aud}  ->  after: {n_total_aud - n_aud}")

    # 4) Confirm (CLI args first for non-interactive use, else stdin)
    import os
    if "--yes" in sys.argv or os.environ.get("CLEANUP_NODE_MODULES_YES") == "1":
        resp = "y"
        print("Auto-confirmed via --yes / CLEANUP_NODE_MODULES_YES=1")
    else:
        resp = input("\nProceed? [y/N]: ").strip().lower()
    if resp not in ("y", "yes"):
        print("Aborted.")
        conn.close()
        return 0

    # 5) Delete
    cur.execute("DELETE FROM artifacts WHERE name LIKE 'node_modules/%'")
    print(f"  deleted {cur.rowcount} artifact rows")
    cur.execute(
        "DELETE FROM audit_log WHERE event_type = 'artifact.registered' "
        "AND json_extract(payload, '$.path') LIKE 'node_modules/%'"
    )
    print(f"  deleted {cur.rowcount} audit_log rows")
    conn.commit()

    # 6) Vacuum to reclaim space (safe; the DB is in WAL mode so this just
    # rebuilds the file. May take a few seconds on a 100MB DB.)
    print("\nRunning VACUUM to reclaim space...")
    cur.execute("VACUUM")
    print("  done.")

    # 7) Verify
    cur.execute("SELECT COUNT(*) FROM artifacts")
    print(f"\nartifacts total after: {cur.fetchone()[0]}")
    cur.execute("SELECT COUNT(*) FROM audit_log")
    print(f"audit_log total after: {cur.fetchone()[0]}")
    cur.execute("SELECT COUNT(*) FROM artifacts WHERE name LIKE 'node_modules/%'")
    print(f"remaining node_modules artifacts: {cur.fetchone()[0]}")

    conn.close()
    print(f"\nBackup at: {BACKUP_PATH}")
    print("If anything looks wrong, restore with:")
    print(f"  cp {BACKUP_PATH} {DB_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
